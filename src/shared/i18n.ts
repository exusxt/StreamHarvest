export type TranslationKey = keyof (typeof STRINGS)['en']

/** Translates a key into the given language, substituting {placeholders}. */
export function translate(lang: Language, key: TranslationKey, vars?: Record<string, string | number>): string {
  const dict = STRINGS[lang]
  let text: string = dict?.[key] ?? STRINGS.en[key] ?? key
  if (vars) {
    for (const [name, value] of Object.entries(vars)) {
      text = text.split(`{${name}}`).join(String(value))
    }
  }
  return text
}
